#!/usr/bin/env python3
"""Generate parts.h and procs.h for the emulated device's driver shim.

parts.h: each part's device attributes, tools/cudadev/attributes/<part>.txt: Nsight Compute's
device__attribute_* captures (the first board's column) or, for the parts not captured, inferred
(sources in the file). Only attributes
whose CU_DEVICE_ATTRIBUTE_ name exists in the toolkit's cuda.h are kept.

procs.h and stubs.c: the driver's exported symbols and entry points by name, and a stub for every
other function cuda.h declares (below).

nvml_stubs.h: every NVML function nvml.h declares that nvml.c does not define, returning
NVML_ERROR_NOT_SUPPORTED, so a program linked against the real library loads.

usage: gen.py <repo root> <cuda.h> <cuda.c> <out dir> [<nvml.h> <nvml.c>]
"""
import os, re
import sys

root, cudah, cudac, out = sys.argv[1:5]
header = open(cudah).read()
enum = set(re.findall(r'\b(CU_DEVICE_ATTRIBUTE_[A-Z0-9_]+)\s*=', header))

# (part, marketing name, target, attribute file)
PARTS = [
    ("h200", "NVIDIA H200", "sm_90a", "tools/cudadev/attributes/h200.txt"),
    ("h100", "NVIDIA H100 80GB HBM3", "sm_90a", "tools/cudadev/attributes/h100.txt"),
    ("h100-pcie", "NVIDIA H100 PCIe", "sm_90a", "tools/cudadev/attributes/h100-pcie.txt"),
    ("h100-nvl", "NVIDIA H100 NVL", "sm_90a", "tools/cudadev/attributes/h100-nvl.txt"),
    ("a100-40", "NVIDIA A100-SXM4-40GB", "sm_80", "tools/cudadev/attributes/a100-40.txt"),
    ("a100-80", "NVIDIA A100-SXM4-80GB", "sm_80", "tools/cudadev/attributes/a100-80.txt"),
    ("rtxpro6000", "NVIDIA RTX PRO 6000 Blackwell Server Edition", "sm_120a",
     "tools/cudadev/attributes/rtxpro6000.txt"),
    ("b200", "NVIDIA B200", "sm_100a", "tools/cudadev/attributes/b200.txt"),
]


def attrs(path):
    d = {}
    for line in open(f"{root}/{path}"):
        if line.startswith("#"):
            continue
        f = line.split()
        if len(f) >= 2 and f[0].startswith("device__attribute_"):
            d[f[0][len("device__attribute_"):]] = f[1]
    return d


with open(f"{out}/parts.h", "w") as o:
    o.write("// Generated by gen.py from the parts' device-attribute captures; do not edit.\n")
    o.write("#include <cuda.h>\n#include <stdint.h>\n#include <stdlib.h>\n#include <string.h>\n\n")
    o.write("typedef struct {\n  const char *name, *marketing, *target;\n  int ccMajor, ccMinor;\n"
            "  uint64_t memBytes;\n  int clockMHz, pciBus, regsPerSm, maxWarpsPerSm, maxBlocksPerSm;\n"
            "  const int (*attrs)[2];\n  int nattrs;\n} Part;\n\n")
    for i, (name, mk, target, path) in enumerate(PARTS):
        d = attrs(path)
        rows = []
        for k, v in sorted(d.items()):
            e = "CU_DEVICE_ATTRIBUTE_" + k.upper()
            if e in enum and re.fullmatch(r"-?\d+", v):
                rows.append(f"  {{{e}, {v}}},")
        o.write(f"static const int attrs{i}[][2] = {{\n" + "\n".join(rows) + "\n};\n")
    o.write("\nstatic const Part parts[] = {\n")
    for i, (name, mk, target, path) in enumerate(PARTS):
        d = attrs(path)
        o.write(f'  {{"{name}", "{mk}", "{target}", {d["compute_capability_major"]}, '
                f'{d["compute_capability_minor"]}, {d["total_memory"]}ull, '
                f'{int(d["clock_rate"]) // 1000}, {d.get("pci_bus_id", "0")}, '
                f'{d["max_registers_per_multiprocessor"]}, {d["max_warps_per_multiprocessor"]}, '
                f'{d["max_blocks_per_multiprocessor"]}, attrs{i}, '
                f'(int)(sizeof attrs{i} / sizeof attrs{i}[0])}},\n')
    o.write("};\n\n")
    o.write("static const Part *findPart(const char *name) {\n"
            "  for (unsigned i = 0; i < sizeof parts / sizeof parts[0]; i++)\n"
            "    if (strcmp(parts[i].name, name) == 0) return &parts[i];\n  return 0;\n}\n\n")
    # NVGPU_LEAN_GPU names a mesh of devices: a part (`h100`), several (`h100,h100`) or a part
    # times a count (`b200x8`); the driver and the management library read it alike.
    o.write("// The devices `spec` names, into out[0..max): their count, or 0 if a name is unknown or\n"
            "// they pass `max`.\n"
            "static int partsOf(const char *spec, const Part **out, int max) {\n"
            "  int n = 0;\n"
            "  const char *s = spec && *spec ? spec : \"h200\";\n"
            "  while (*s) {\n"
            "    char name[64];\n"
            "    size_t len = strcspn(s, \",\");\n"
            "    if (len == 0 || len >= sizeof name) return 0;\n"
            "    memcpy(name, s, len);\n"
            "    name[len] = 0;\n"
            "    s += len + (s[len] == ',');\n"
            "    int count = 1;\n"
            "    char *x = strrchr(name, 'x');\n"
            "    if (x && x[1] >= '1' && x[1] <= '9' && strspn(x + 1, \"0123456789\") == strlen(x + 1)) {\n"
            "      count = atoi(x + 1);\n"
            "      *x = 0;\n"
            "    }\n"
            "    const Part *p = findPart(name);\n"
            "    if (!p || n + count > max) return 0;\n"
            "    for (int i = 0; i < count; i++) out[n++] = p;\n"
            "  }\n"
            "  return n;\n"
            "}\n\n")
    o.write("static int partAttribute(const Part *p, int a, int *v) {\n"
            "  for (int i = 0; i < p->nattrs; i++)\n"
            "    if (p->attrs[i][0] == a) { *v = p->attrs[i][1]; return 1; }\n"
            "  *v = 0;\n  return 1;\n}\n")

# procs.h (included at the end of cuda.c) and stubs.c: the driver's exported symbols and its
# entry points by name. Frameworks resolve driver functions both ways: by symbol (XLA's stub
# library dlsyms each, `cuMemAlloc_v2`) and through cuGetProcAddress (cudart, by the name without
# the ABI suffix, `cuMemAlloc`). So:
# - each function cuda.c defines is found under its own name and the name cuda.h's macro gives it
#   (cuMemAlloc -> its symbol cuMemAlloc_v2); a per-thread-stream form (`_ptds`, `_ptsz`) is an
#   alias of the symbol, the legacy default stream standing for the per-thread one;
# - every other function cuda.h declares is a stub in stubs.c (a translation unit without cuda.h,
#   so a stub's type does not clash with the declaration) that names itself and returns
#   CUDA_ERROR_NOT_SUPPORTED: a program learns which function it used that the device lacks.
src = open(cudac).read()
for inc in re.findall(r'^#include "(\w+\.h)"', src, re.M):
    path = os.path.join(os.path.dirname(cudac), inc)
    if os.path.exists(path):
        src += open(path).read()
version = int(re.search(r'#define\s+CUDA_VERSION\s+(\d+)', header).group(1))


def compiled(text):
    """The lines of `text` the compiler sees under this cuda.h: blocks under `#if CUDA_VERSION OP N`
    (and their `#else`) kept or dropped by the header's version; other conditionals kept whole."""
    keep, stack = [], []  # stack: (this block's branch taken, a CUDA_VERSION condition)
    for line in text.splitlines():
        t = line.strip()
        m = re.match(r'#if\s+CUDA_VERSION\s*(<|>=|>|<=|==)\s*(\d+)\s*$', t)
        if m:
            op, n = m.group(1), int(m.group(2))
            stack.append(({"<": version < n, ">=": version >= n, ">": version > n, "<=": version <= n,
                           "==": version == n}[op], True))
            continue
        if t.startswith("#if"):
            stack.append((True, False))
        elif t.startswith("#else") and stack and stack[-1][1]:
            stack[-1] = (not stack[-1][0], True)
            continue
        elif t.startswith("#endif") and stack:
            if stack.pop()[1]:
                continue
        if all(taken for taken, _ in stack):
            keep.append(line)
    return "\n".join(keep)


src = compiled(src)
defined = set(re.findall(r'^CUresult CUDAAPI (cu\w+)\(', src, re.M))
# legacy.c (its own translation unit, without cuda.h's renaming macros): the older ABIs it defines
# under their own names.
legacyc = os.path.join(os.path.dirname(cudac), "legacy.c")
legacyDefined = set(re.findall(r'^CUresult (cu\w+)\(', open(legacyc).read(), re.M)) if os.path.exists(legacyc) else set()


def params(text):
    """A prototype's parameter types, without the parameters' names or spacing."""
    out = []
    for p in text.split(","):
        p = " ".join(p.replace("*", " * ").split())
        words = p.split(" ")
        if len(words) > 1 and words[-1] not in ("*", "void") and re.fullmatch(r"\w+", words[-1]):
            words = words[:-1]
        out.append(" ".join(words))
    return out


# cuda.h's last internal section declares the older ABIs under their original names (the ones its
# macros rename): an older ABI whose parameters are the current one's is exported as an alias of it.
internalAt = header.rfind("#if defined(__CUDA_API_VERSION_INTERNAL)")
main, internal = header[:internalAt], header[internalAt:]
proto = r'CUresult\s+CUDAAPI\s+(cu\w+)\s*\(([^;]*?)\)\s*;'
mainProto = {}
for n, ps in re.findall(proto, main, re.S):
    mainProto.setdefault(n, params(ps))
oldProto = {}
for n, ps in re.findall(proto, internal, re.S):
    oldProto.setdefault(n, params(ps))
macro = dict(re.findall(r'#define\s+(cu\w+)\s+(?:__CUDA_API_PT\w+\()?(cu\w+)', header))
perThread = dict(re.findall(r'#define\s+(cu\w+)\s+__CUDA_API_(PTDS|PTSZ)\(', header))
declared = set(re.findall(r'CUresult\s+CUDAAPI\s+(cu\w+)\s*\(', header))
symbol = {f: macro.get(f, f) for f in defined}   # a definition's exported symbol
NOT_SUPPORTED = 801  # CUDA_ERROR_NOT_SUPPORTED
with open(f"{out}/procs.h", "w") as o:
    o.write("// Generated by gen.py: the driver's per-thread-stream aliases and its entry points by\n"
            "// name. Do not edit.\n")
    entries, exported = [], set(symbol.values()) | {"cuGetProcAddress", "cuGetProcAddress_v2"}
    for f in sorted(defined - {"cuGetProcAddress"}):
        entries.append((f, f))
        if symbol[f] != f:
            entries.append((symbol[f], f))
    for alias, target in sorted(macro.items()):
        if alias != target and target in defined and alias not in defined:
            entries.append((alias, target))
    for f in sorted(defined):
        if f in perThread:
            suffix = "_ptds" if perThread[f] == "PTDS" else "_ptsz"
            name = symbol[f] + suffix
            o.write(f'__asm__(".globl {name}\\n.set {name}, {symbol[f]}");\n')
            entries.append((name, f))
            exported.add(name)
    # An older ABI's name (the one cuda.h's macro renames a definition from) with the current ABI's
    # parameters: an alias of the definition's symbol.
    for f in sorted(defined):
        old = f
        if symbol[f] != old and old in oldProto and old in mainProto and oldProto[old] == mainProto[old] \
                and old not in exported and old not in legacyDefined:
            o.write(f'__asm__(".globl {old}\\n.set {old}, {symbol[f]}");\n')
            exported.add(old)
    exported |= legacyDefined
    names = {n for n, _ in entries} | {"cuGetProcAddress"}
    # Every other name cuda.h declares, or its macros rename to, that nothing exports: a stub.
    stubs = sorted(n for n in (declared | set(macro.values())) - exported
                   if n.startswith("cu") and not n.endswith(("_ptds", "_ptsz")) and n != "cuGetProcAddress")
    for n in stubs:
        o.write(f'extern int stub_{n}(void) __asm__("{n}");\n')
    o.write("static const struct { const char *name; void *fn; } procs[] = {\n")
    for n, f in entries:
        o.write(f'  {{"{n}", (void *){f}}},\n')
    o.write('  {"cuGetProcAddress", (void *)cuGetProcAddress},\n')
    for n in stubs:
        if n in names:
            continue  # asked for by name, cuGetProcAddress gives the definition
        o.write(f'  {{"{n}", (void *)stub_{n}}},\n')
        # cudart asks for a function by the name without its ABI suffix.
        base = re.sub(r'_v\d+$', '', n)
        if base != n and base not in names and base not in stubs:
            o.write(f'  {{"{base}", (void *)stub_{n}}},\n')
    o.write("};\n\nstatic void *findProc(const char *name) {\n"
            "  for (unsigned i = 0; i < sizeof procs / sizeof procs[0]; i++)\n"
            "    if (strcmp(procs[i].name, name) == 0) return procs[i].fn;\n  return 0;\n}\n")
# trace.h (included after procs.h): with NVGPU_LEAN_TRACE set, cuGetProcAddress hands out, for
# each entry point, a trampoline that calls it and logs its name and result as it returns (every
# call that fails; every call with NVGPU_LEAN_TRACE=2): which call of a library's failed is what
# its own error does not say. x86-64 System V: a trampoline keeps every argument register and the
# stack as the caller left them, puts its return stub in place of the caller's return address
# (kept on a per-thread stack), and jumps to the function.
COMMON = r"""
nvgpu_trace_common:
 sub $200, %rsp
 mov %rdi, 0(%rsp)
 mov %rsi, 8(%rsp)
 mov %rdx, 16(%rsp)
 mov %rcx, 24(%rsp)
 mov %r8, 32(%rsp)
 mov %r9, 40(%rsp)
 movdqu %xmm0, 48(%rsp)
 movdqu %xmm1, 64(%rsp)
 movdqu %xmm2, 80(%rsp)
 movdqu %xmm3, 96(%rsp)
 movdqu %xmm4, 112(%rsp)
 movdqu %xmm5, 128(%rsp)
 movdqu %xmm6, 144(%rsp)
 movdqu %xmm7, 160(%rsp)
 mov %eax, %edi
 mov 200(%rsp), %rsi
 call nvgpu_trace_enter
 mov %rax, %r11
 mov 0(%rsp), %rdi
 mov 8(%rsp), %rsi
 mov 16(%rsp), %rdx
 mov 24(%rsp), %rcx
 mov 32(%rsp), %r8
 mov 40(%rsp), %r9
 movdqu 48(%rsp), %xmm0
 movdqu 64(%rsp), %xmm1
 movdqu 80(%rsp), %xmm2
 movdqu 96(%rsp), %xmm3
 movdqu 112(%rsp), %xmm4
 movdqu 128(%rsp), %xmm5
 movdqu 144(%rsp), %xmm6
 movdqu 160(%rsp), %xmm7
 add $200, %rsp
 lea nvgpu_trace_back(%rip), %rax
 mov %rax, (%rsp)
 jmp *%r11
nvgpu_trace_back:
 push %rax
 sub $8, %rsp
 mov %eax, %edi
 call nvgpu_trace_leave
 mov %rax, %r11
 add $8, %rsp
 pop %rax
 jmp *%r11
"""
with open(f"{out}/trace.h", "w") as o:
    o.write("// Generated by gen.py: tracing trampolines for the entry points of procs.h. Do not edit.\n")
    n = len(entries) + 1 + len(stubs) + 64  # and the runtime tables' entries (runtime_tables.h)
    o.write(f"#define TRACED {n}\n")
    o.write("static void *traceTarget[TRACED];\nstatic const char *traceName[TRACED];\n")
    o.write("void *nvgpu_trace_enter(long i, void *ret);\nvoid *nvgpu_trace_leave(int result);\n")
    lines = [".text"]
    for i in range(n):
        lines += [f".hidden nvgpu_trace_{i}", f".globl nvgpu_trace_{i}", f"nvgpu_trace_{i}:",
                  f" movl ${i}, %eax", " jmp nvgpu_trace_common"]
    lines += COMMON.strip("\n").split("\n")
    o.write("__asm__(\n" + "".join(f'  "{l}\\n"\n' for l in lines) + ");\n")
    for i in range(n):
        o.write(f"void nvgpu_trace_{i}(void);\n")
    o.write("static void *const traceTramp[TRACED] = {\n")
    o.write(",\n".join(f"  (void *)nvgpu_trace_{i}" for i in range(n)) + "\n};\n")

with open(f"{out}/stubs.c", "w") as o:
    o.write("// Generated by gen.py: the driver functions the emulated device does not provide. Do not edit.\n"
            "void nvgpu_unsupported(const char *name);\n")
    for n in stubs:
        o.write(f'int {n}(void) {{ nvgpu_unsupported("{n}"); return {NOT_SUPPORTED}; }}\n')

if len(sys.argv) > 6:
    nvmlh, nvmlc = sys.argv[5:7]
    full = open(nvmlh).read()
    decl = r'nvmlReturn_t\s+DECLDIR\s+(nvml\w+)\s*\(([^;]*?)\)\s*;'
    # The deprecated, unversioned names (nvmlInit, nvmlDeviceGetHandleByIndex, ...): older ABIs
    # NVML's library still exports, which libraries dlsym by name (NVSHMEM's host library and
    # NCCL's ask for `nvmlInit` and `nvmlDeviceGetHandleByIndex`; a NULL from dlsym crashes them).
    legacy = []
    for block in re.findall(r'#ifdef NVML_NO_UNVERSIONED_FUNC_DEFS\n(.*?)#endif', full, re.S):
        legacy += re.findall(decl, block, re.S)
    # Declarations outside that block, whose names cuda.h-style macros map to the versioned ones.
    h = re.sub(r'#if defined\(NVML_NO_UNVERSIONED_FUNC_DEFS\).*?#endif', '', full, flags=re.S)
    nmacro = dict(re.findall(r'#define\s+(nvml\w+)\s+(nvml\w+)', h))
    decls = re.findall(decl, h, re.S)
    done = {nmacro.get(f, f) for f in re.findall(r'^nvmlReturn_t DECLDIR (nvml\w+)\(', open(nvmlc).read(), re.M)}
    params_of = {nmacro.get(n, n): " ".join(p.split()) for n, p in decls}
    with open(f"{out}/nvml_stubs.h", "w") as o:
        o.write("// Generated by gen.py: the NVML functions nvml.c does not define, and the deprecated\n"
                "// unversioned ones. Do not edit.\n"
                "static nvmlReturn_t unsupported(const char *f) {\n"
                "  if (getenv(\"NVGPU_LEAN_TRACE\")) fprintf(stderr, \"nvgpu-lean: %s is not supported by the emulated NVML\\n\", f);\n"
                "  return NVML_ERROR_NOT_SUPPORTED;\n}\n")
        for name, params in decls:
            real = nmacro.get(name, name)
            if real in done:
                continue
            done.add(real)
            o.write(f"nvmlReturn_t DECLDIR {name}({params}) {{ return unsupported(\"{name}\"); }}\n")
        # An unversioned name whose successor takes the same arguments and fills no structure
        # (whose older layout may be smaller) calls it; the others are not supported. Defined after
        # nvml.h's macros are undone.
        same_abi = {"nvmlInit", "nvmlDeviceGetCount", "nvmlDeviceGetHandleByIndex", "nvmlDeviceGetHandleByPciBusId"}
        for name, params in legacy:
            if name in done:
                continue
            done.add(name)
            o.write(f"#undef {name}\n")
            succ = nmacro.get(name)
            args = [re.findall(r'(\w+)\s*(?:\[\s*\w*\s*\])?\s*$', a.strip())[0] for a in params.split(",")
                    if a.strip() and a.strip() != "void"]
            if name in same_abi and succ and params_of.get(succ) == " ".join(params.split()):
                o.write(f"nvmlReturn_t DECLDIR {name}({params}) {{ return {succ}({', '.join(args)}); }}\n")
            else:
                o.write(f"nvmlReturn_t DECLDIR {name}({params}) {{ return unsupported(\"{name}\"); }}\n")
